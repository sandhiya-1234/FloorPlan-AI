"""
Per-image prediction record shared by every evaluated system
(zero-shot Qwen2.5-VL, fine-tuned Qwen2.5-VL + LoRA, OpenCV baseline).

One file per image: ``<stem>.pred.json``. The evaluator reads these files only; it never
calls a model. The constructor enforces the project's integrity rule structurally:
a failed record cannot carry a prediction, so failures can never be papered over with
default geometry.
"""

import json
from pathlib import Path
from typing import Any, Dict, Optional

RECORD_VERSION = 1
FAILURE_STAGES = ("load", "generate", "json_parse", "schema_validation")


def make_record(
    *,
    image: str,
    system: str,
    status: str,
    failure_stage: Optional[str] = None,
    error: Optional[str] = None,
    raw_output: Optional[str] = None,
    prediction_raw: Optional[Dict[str, Any]] = None,
    prediction: Optional[Dict[str, Any]] = None,
    postprocess_diagnostics: Optional[Dict[str, Any]] = None,
    meta: Optional[Dict[str, Any]] = None,
) -> Dict[str, Any]:
    """
    Build a prediction record.

    raw_output          exact text generated by a generative model (None for non-generative systems)
    prediction_raw      schema-validated prediction BEFORE geometric refinement
    prediction          final prediction (after refinement, or identical to prediction_raw)
    meta                model/adapter identity, timings, preprocessing transform, etc.
    """
    if status not in ("ok", "failed"):
        raise ValueError(f"status must be 'ok' or 'failed', got {status!r}")
    if status == "ok":
        if prediction is None:
            raise ValueError("an 'ok' record requires a prediction")
        if failure_stage or error:
            raise ValueError("an 'ok' record cannot carry failure_stage/error")
    else:
        if failure_stage not in FAILURE_STAGES:
            raise ValueError(f"failure_stage must be one of {FAILURE_STAGES}, got {failure_stage!r}")
        if not error:
            raise ValueError("a failed record requires error text")
        if prediction is not None or prediction_raw is not None:
            raise ValueError("a failed record must not carry a prediction (no default geometry)")
    return {
        "record_version": RECORD_VERSION,
        "image": image,
        "system": system,
        "status": status,
        "failure_stage": failure_stage,
        "error": error,
        "raw_output": raw_output,
        "prediction_raw": prediction_raw,
        "prediction": prediction,
        "postprocess_diagnostics": postprocess_diagnostics or {},
        "meta": meta or {},
    }


def record_path(out_dir: Path, image_name: str) -> Path:
    return Path(out_dir) / f"{Path(image_name).stem}.pred.json"


def write_record(path: Path, record: Dict[str, Any]) -> None:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        json.dump(record, f, indent=2)


def load_record(path: Path) -> Dict[str, Any]:
    with open(path, "r", encoding="utf-8") as f:
        rec = json.load(f)
    if rec.get("record_version") != RECORD_VERSION:
        raise ValueError(f"{path}: unsupported record_version {rec.get('record_version')!r}")
    return rec
